// Package projection renders the files Polterware writes into checkouts: one
// Markdown file per Decision under docs/decision/ and one generated block in AGENTS.md.
// The store stays the source of truth; nothing here reads a checkout back.
// It is pure so the export composition only moves bytes.
package projection

import (
	"fmt"
	"regexp"
	"slices"
	"strings"

	lifecycle "github.com/polterware/polterware/backend/domains/decision"
	"github.com/polterware/polterware/backend/domains/polter"
	"github.com/polterware/polterware/backend/domains/structure"
	"github.com/polterware/polterware/backend/domains/work"
)

const (
	// BlockBegin and BlockEnd delimit the generated AGENTS.md block. Export
	// replaces what lies between them and leaves the rest of the file alone.
	BlockBegin = "<!-- polterware:begin generated -->"
	BlockEnd   = "<!-- polterware:end generated -->"

	// DecisionDir is where Decision projections go, relative to a checkout.
	DecisionDir = "docs/decision"
	// LegacyDecisionDir held the projections before Decisions had their name.
	// Export removes the files it wrote there.
	LegacyDecisionDir = "docs/verdict"
	// AgentsFile is the agent instructions file, relative to a checkout.
	AgentsFile = "AGENTS.md"
)

// Decision is one decision record from the project store. A principle
// applies to the whole project, so every checkout's block lists it.
type Decision struct {
	ID        string
	Title     string
	Body      string
	Status    string
	Principle bool
}

var (
	decisionMarker       = regexp.MustCompile(`^<!-- polterware:decision (\S+) `)
	legacyDecisionMarker = regexp.MustCompile(`^<!-- polterware:verdict \S+ `)
	decisionFileName     = regexp.MustCompile(`^(\d{4})-[^/]*\.md$`)
)

const maxSlugRunes = 60

// Govern assigns each Decision to the checkouts it governs: the repo of every
// active node that cites it in decisions:. A Decision no active node cites
// governs the project root (""). The result is keyed by checkout name.
func Govern(nodes []structure.Node, decisions []Decision) map[string][]Decision {
	out := map[string][]Decision{}
	for _, decision := range decisions {
		repos := map[string]bool{}
		for _, node := range nodes {
			if node.Status == structure.NodeRemoved {
				continue
			}
			for _, ref := range node.Decisions {
				if Cites(ref, decision) {
					repos[node.Repo] = true
				}
			}
		}
		if len(repos) == 0 {
			repos[""] = true
		}
		for repo := range repos {
			out[repo] = append(out[repo], decision)
		}
	}
	for repo := range out {
		sortDecisions(out[repo])
	}
	return out
}

// Cites reports whether a decisions: entry names decision, by id or Decision number.
func Cites(ref string, decision Decision) bool {
	return polter.CitesDecision(ref, decision.ID, decision.Title)
}

// DecisionFile returns the file name under docs/decision/ and the projected content.
// ok is false when the title carries no Decision number.
func DecisionFile(decision Decision) (name, content string, ok bool) {
	number, ok := polter.ParseDecisionNumber(decision.Title)
	if !ok {
		return "", "", false
	}
	slug := slugify(lifecycle.StripNumber(decision.Title))
	if slug == "" {
		slug = "decision"
	}
	name = fmt.Sprintf("%04d-%s.md", number, slug)

	var b strings.Builder
	fmt.Fprintf(&b, "<!-- polterware:decision %s generated by polterware export; edits here are replaced on the next export -->\n", decision.ID)
	body := strings.TrimSpace(decision.Body)
	if !strings.HasPrefix(body, "# ") {
		fmt.Fprintf(&b, "# %s\n\n", decision.Title)
	} else if title, rest, found := strings.Cut(body, "\n"); found {
		b.WriteString(title + "\n\n")
		body = strings.TrimSpace(rest)
	} else {
		b.WriteString(body + "\n\n")
		body = ""
	}
	if decision.Status != "" {
		fmt.Fprintf(&b, "Lifecycle status: %s\n\n", decision.Status)
	}
	if body != "" {
		b.WriteString(body)
		b.WriteString("\n")
	}
	return name, b.String(), true
}

// DecisionMarker returns the Decision id a projected file was written for, or false
// when content is not a Polterware projection.
func DecisionMarker(content string) (string, bool) {
	m := decisionMarker.FindStringSubmatch(content)
	if m == nil {
		return "", false
	}
	return m[1], true
}

// LegacyDecisionMarker reports whether content is a projection export wrote
// under LegacyDecisionDir.
func LegacyDecisionMarker(content string) bool {
	return legacyDecisionMarker.MatchString(content)
}

// DecisionFileNumber returns the four-digit number of a `NNNN-*.md` file name.
func DecisionFileNumber(name string) (string, bool) {
	m := decisionFileName.FindStringSubmatch(name)
	if m == nil {
		return "", false
	}
	return m[1], true
}

// Block renders the AGENTS.md block for checkout ("" is the project root):
// the project's principles, the Structure nodes placed in it with their kind
// and technology, the decisions that govern it or its nodes, the invariants of
// those nodes and their ancestors, and how to read the brief for a file.
func Block(checkout string, nodes []structure.Node, governed []Decision, all []Decision) string {
	applicable := applicableNodes(checkout, nodes)

	var own []string
	for _, node := range applicable {
		if node.Repo != checkout {
			continue
		}
		line := fmt.Sprintf("- %s (%s) %s", node.Path, node.Level, node.Title)
		for _, part := range []string{node.Kind, node.Tech} {
			if part != "" {
				line += " · " + part
			}
		}
		if node.Folder != "" {
			line += " · path: " + node.Folder
		}
		own = append(own, line)
	}

	var principles []string
	for _, decision := range all {
		if decision.Principle {
			principles = append(principles, "- "+lifecycle.StripNumber(decision.Title))
		}
	}
	var decisions []Decision
	for _, decision := range governed {
		if !decision.Principle {
			decisions = append(decisions, decision)
		}
	}
	for _, node := range applicable {
		for _, ref := range node.Decisions {
			for _, decision := range all {
				if Cites(ref, decision) && !decision.Principle && !containsDecision(decisions, decision.ID) {
					decisions = append(decisions, decision)
				}
			}
		}
	}
	sortDecisions(decisions)

	var invariants []string
	for _, node := range applicable {
		for _, inv := range node.Invariants {
			if inv.State == work.InvariantActive {
				invariants = append(invariants, fmt.Sprintf("- %s (from %s)", inv.Text, node.Path))
			}
		}
	}

	var b strings.Builder
	b.WriteString(BlockBegin + "\n")
	b.WriteString("## Polterware project context\n\n")
	b.WriteString("Generated from the Polterware project store by `polterware export`, or on every change when AGENTS.md sync is on. Edits inside this block are replaced; change the source with `polterware apply`. Before you work on a card, a Structure node, or a file, read `polterware brief <slug|path|file>`.\n")
	if len(principles)+len(own)+len(decisions)+len(invariants) == 0 {
		b.WriteString("\nNo principles, Structure nodes, decisions, or invariants apply to this checkout.\n")
	}
	writeSection(&b, "Principles", principles)
	writeSection(&b, "Structure", own)
	var decisionLines []string
	for _, decision := range decisions {
		line := "- " + decision.Title
		if decision.Status != "" {
			line += " (" + decision.Status + ")"
		}
		decisionLines = append(decisionLines, line)
	}
	writeSection(&b, "Decisions", decisionLines)
	writeSection(&b, "Invariants", invariants)
	b.WriteString(BlockEnd + "\n")
	return b.String()
}

// ReplaceBlock puts block into an AGENTS.md body. An existing block is
// replaced in place; otherwise the block is appended. A begin sentinel
// without its end is an error, so a broken file is never truncated.
func ReplaceBlock(existing, block string) (string, error) {
	begin := strings.Index(existing, BlockBegin)
	if begin < 0 {
		if strings.TrimSpace(existing) == "" {
			return block, nil
		}
		return strings.TrimRight(existing, "\n") + "\n\n" + block, nil
	}
	rest := existing[begin:]
	end := strings.Index(rest, BlockEnd)
	if end < 0 {
		return "", fmt.Errorf("%s has %q without %q: fix the file by hand", AgentsFile, BlockBegin, BlockEnd)
	}
	after := rest[end+len(BlockEnd):]
	after = strings.TrimPrefix(after, "\n")
	return existing[:begin] + block + after, nil
}

// applicableNodes returns active nodes placed in checkout plus their active
// ancestors, in graph order, so inherited invariants reach every checkout.
func applicableNodes(checkout string, nodes []structure.Node) []structure.Node {
	byID := map[string]structure.Node{}
	for _, node := range nodes {
		byID[node.ID] = node
	}
	keep := map[string]bool{}
	for _, node := range nodes {
		if node.Status == structure.NodeRemoved || node.Repo != checkout {
			continue
		}
		keep[node.ID] = true
		for parent, ok := byID[node.ParentID]; ok && parent.Status != structure.NodeRemoved; parent, ok = byID[parent.ParentID] {
			keep[parent.ID] = true
		}
	}
	var out []structure.Node
	for _, node := range nodes {
		if keep[node.ID] {
			out = append(out, node)
		}
	}
	return out
}

func writeSection(b *strings.Builder, title string, lines []string) {
	if len(lines) == 0 {
		return
	}
	fmt.Fprintf(b, "\n%s:\n", title)
	for _, line := range lines {
		b.WriteString(line)
		b.WriteString("\n")
	}
}

func containsDecision(list []Decision, id string) bool {
	return slices.ContainsFunc(list, func(decision Decision) bool { return decision.ID == id })
}

// sortDecisions orders by Decision number, then title; unnumbered records go last.
func sortDecisions(list []Decision) {
	slices.SortStableFunc(list, func(a, b Decision) int {
		na, oka := polter.ParseDecisionNumber(a.Title)
		nb, okb := polter.ParseDecisionNumber(b.Title)
		switch {
		case oka && okb && na != nb:
			return na - nb
		case oka != okb:
			if oka {
				return -1
			}
			return 1
		}
		return strings.Compare(a.Title, b.Title)
	})
}

func slugify(title string) string {
	slug := strings.ReplaceAll(work.NormalizeText(title), " ", "-")
	runes := []rune(slug)
	if len(runes) > maxSlugRunes {
		slug = strings.TrimRight(string(runes[:maxSlugRunes]), "-")
	}
	return slug
}
