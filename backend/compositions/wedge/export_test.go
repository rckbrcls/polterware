package wedge_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
	"time"

	"github.com/polterware/polterware/backend/compositions/wedge"
	"github.com/polterware/polterware/backend/domains/knowledge"
	"github.com/polterware/polterware/backend/domains/projection"
	storepkg "github.com/polterware/polterware/backend/providers/sqlite"
)

// legacyMarker opens a projection written before Decisions had their name.
const legacyMarker = "<!-- polterware:verdict "

const exportGraph = `---
polter: 1
summary: Shop graph
rationale: Export test
---
# shop: Shop
level: domain · dir: {root} · decisions: Decision 0001

! Money is integer cents

# shop/auth: Auth
level: component · repo: api · path: src/auth · decisions: Decision 0002

! Tokens expire in 15 minutes
`

func TestExportProjections(t *testing.T) {
	store, err := storepkg.New(filepath.Join(t.TempDir(), "export.db"))
	if err != nil {
		t.Fatal(err)
	}
	defer store.Close()
	root, apiDir := filepath.Join(t.TempDir(), "shop"), filepath.Join(t.TempDir(), "api")
	for _, dir := range []string{root, apiDir} {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			t.Fatal(err)
		}
	}
	project, err := initWithRepo(store, "Shop", root)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := wedge.EnsureRepository(store, project.ID, apiDir); err != nil {
		t.Fatal(err)
	}
	now := time.Now().UTC()
	for _, item := range []knowledge.Item{
		{ID: "decision-cents", Title: "Decision 0001: Integer cents", Body: "## Decision\n\nStore cents.", Status: "accepted"},
		{ID: "decision-tokens", Title: "Decision 0002: Short tokens", Body: "## Decision\n\nShort tokens."},
		{ID: "decision-hand", Title: "Decision 0003: Hand written", Body: "From the store."},
	} {
		item.ProjectID, item.Kind, item.CreatedAt, item.UpdatedAt = project.ID, "decision", now, now
		if err := store.SaveKnowledge(item); err != nil {
			t.Fatal(err)
		}
	}
	if _, err := wedge.ApplyPolter(store, wedge.ApplyInput{ProjectID: project.ID, Text: strings.ReplaceAll(exportGraph, "{root}", root), AutoStartLabel: "cli"}); err != nil {
		t.Fatal(err)
	}

	// A hand-written Decision with the same number and surrounding AGENTS.md text stay.
	handDecision := filepath.Join(root, "docs", "decision", "0003-hand-written.md")
	writeFile(t, handDecision, "# Decision 0003: Hand written\n\nOriginal.\n")
	agents := filepath.Join(root, "AGENTS.md")
	writeFile(t, agents, "# Agents\n\n"+projection.BlockBegin+"\nstale\n"+projection.BlockEnd+"\n\n## Tail\nKeep me.\n")

	// Projections export wrote under the legacy directory are removed; hand-written
	// files there stay, and an emptied directory goes.
	legacyRoot := filepath.Join(root, filepath.FromSlash(projection.LegacyDecisionDir))
	legacyAPI := filepath.Join(apiDir, filepath.FromSlash(projection.LegacyDecisionDir))
	writeFile(t, filepath.Join(legacyRoot, "0001-integer-cents.md"), legacyMarker+"decision-cents generated by polterware export -->\n# Old\n")
	writeFile(t, filepath.Join(legacyRoot, "notes.md"), "# Mine\n")
	writeFile(t, filepath.Join(legacyAPI, "0002-short-tokens.md"), legacyMarker+"decision-tokens generated by polterware export -->\n")

	dry, err := wedge.ExportProjections(store, project.ID, true)
	if err != nil {
		t.Fatal(err)
	}
	if len(dry) == 0 || fileExists(filepath.Join(apiDir, "AGENTS.md")) || !fileExists(filepath.Join(legacyAPI, "0002-short-tokens.md")) {
		t.Fatalf("dry run wrote files: %+v", dry)
	}

	files, err := wedge.ExportProjections(store, project.ID, false)
	if err != nil {
		t.Fatal(err)
	}
	if got := readFile(t, handDecision); got != "# Decision 0003: Hand written\n\nOriginal.\n" {
		t.Fatalf("hand-written Decision changed: %q", got)
	}
	if !hasProjection(files, "shop", "docs/decision/0003-hand-written.md", wedge.ProjectionSkip) {
		t.Fatalf("hand-written Decision should be skipped: %+v", files)
	}
	if !strings.Contains(readFile(t, filepath.Join(root, "docs", "decision", "0001-integer-cents.md")), "Store cents.") {
		t.Fatalf("root Decision missing")
	}
	if !strings.Contains(readFile(t, filepath.Join(apiDir, "docs", "decision", "0002-short-tokens.md")), "Short tokens.") {
		t.Fatalf("api Decision missing")
	}
	if fileExists(filepath.Join(root, "docs", "decision", "0002-short-tokens.md")) {
		t.Fatalf("Decision 0002 governs api only")
	}
	if fileExists(filepath.Join(legacyRoot, "0001-integer-cents.md")) || !fileExists(filepath.Join(legacyRoot, "notes.md")) || fileExists(legacyAPI) {
		t.Fatalf("legacy projections: %+v", files)
	}
	if !hasProjection(files, "api", projection.LegacyDecisionDir+"/0002-short-tokens.md", wedge.ProjectionRemove) {
		t.Fatalf("legacy removal not reported: %+v", files)
	}

	rootAgents := readFile(t, agents)
	if strings.Contains(rootAgents, "stale") || !strings.HasPrefix(rootAgents, "# Agents\n\n"+projection.BlockBegin) ||
		!strings.HasSuffix(rootAgents, projection.BlockEnd+"\n\n## Tail\nKeep me.\n") {
		t.Fatalf("root AGENTS.md:\n%s", rootAgents)
	}
	apiAgents := readFile(t, filepath.Join(apiDir, "AGENTS.md"))
	if !strings.Contains(apiAgents, "Tokens expire in 15 minutes (from shop/auth)") || !strings.Contains(apiAgents, "Money is integer cents (from shop)") {
		t.Fatalf("api AGENTS.md:\n%s", apiAgents)
	}

	// Edits in the checkout do not flow back; re-export replaces them.
	writeFile(t, agents, strings.Replace(rootAgents, "Money is integer cents", "Money is floats", 1))
	projected := filepath.Join(root, "docs", "decision", "0001-integer-cents.md")
	writeFile(t, projected, readFile(t, projected)+"\nLocal edit.\n")
	if _, err := wedge.ExportProjections(store, project.ID, false); err != nil {
		t.Fatal(err)
	}
	if readFile(t, agents) != rootAgents || strings.Contains(readFile(t, projected), "Local edit.") {
		t.Fatalf("re-export must replace checkout edits")
	}
	again, err := wedge.ExportProjections(store, project.ID, false)
	if err != nil {
		t.Fatal(err)
	}
	for _, file := range again {
		if file.Action == wedge.ProjectionWrite {
			t.Fatalf("second export should change nothing: %+v", file)
		}
	}
}

func hasProjection(files []wedge.ProjectionFile, repo, path, action string) bool {
	for _, file := range files {
		if file.Repo == repo && file.Path == path && file.Action == action {
			return true
		}
	}
	return false
}

func writeFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func readFile(t *testing.T, path string) string {
	t.Helper()
	body, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(body)
}

func fileExists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}
