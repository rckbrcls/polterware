#!/usr/bin/env bash
set -euo pipefail
NATIVE="$(cd "$(dirname "$0")/.." && pwd)"
DESKTOP="$(cd "$NATIVE/.." && pwd)"
bash "$NATIVE/scripts/build.sh"
ELECTRON_PKG="$(node -p "require('node:path').dirname(require.resolve('electron/package.json',{paths:[process.argv[1]]}))" "$DESKTOP")"
if [[ ! -d "$ELECTRON_PKG/dist/Electron.app" ]]; then
  node "$ELECTRON_PKG/install.js"
fi
ELECTRON_APP="$ELECTRON_PKG/dist/Electron.app"
[[ -d "$ELECTRON_APP" ]] || { echo "Electron.app missing after install: $ELECTRON_APP" >&2; exit 1; }
APP="$NATIVE/build/lifecycle/Polterware Notes.app"
RESULT="$NATIVE/build/lifecycle-result.json"
[[ ! -e "$RESULT" ]] || rm "$RESULT"
mkdir -p "$(dirname "$APP")"
ditto "$ELECTRON_APP" "$APP"
PLIST="$APP/Contents/Info.plist"
/usr/libexec/PlistBuddy -c 'Set :CFBundleIdentifier com.polterware.notes.native-lifecycle' "$PLIST"
/usr/libexec/PlistBuddy -c 'Set :CFBundleName Polterware Notes Native Lifecycle' "$PLIST"
/usr/libexec/PlistBuddy -c 'Set :CFBundleDisplayName Polterware Notes Native Lifecycle' "$PLIST"
/usr/libexec/PlistBuddy -c 'Add :LSUIElement bool true' "$PLIST" 2>/dev/null || /usr/libexec/PlistBuddy -c 'Set :LSUIElement true' "$PLIST"
CODE="$APP/Contents/Resources/app"
mkdir -p "$CODE"
cp "$NATIVE/tests/lifecycle.cjs" "$CODE/main.cjs"
cp "$NATIVE/build/notify.node" "$CODE/notify.node"
printf '{"name":"notes-notify-lifecycle-test","version":"0.0.0","main":"main.cjs"}\n' > "$CODE/package.json"
node -e 'require("node:fs").writeFileSync(process.argv[1], JSON.stringify({result:process.argv[2]}))' "$CODE/config.json" "$RESULT"
codesign --force --deep --sign - --identifier com.polterware.notes.native-lifecycle "$APP"
codesign --verify --deep --strict "$APP"
open -g -j -W -n -a "$APP"
node -e 'const fs=require("node:fs"); const result=JSON.parse(fs.readFileSync(process.argv[1],"utf8")); console.log(JSON.stringify(result)); if(!result.passed) process.exit(1);' "$RESULT"
